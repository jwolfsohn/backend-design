#!/usr/bin/env node
// render-env-example.mjs — generate a copy-pasteable .env template at the project root.
//
// Reads .backend-design/state/*.json + .backend-design/config.json and emits
// `backend-design.env.example`. Each var has a one-line comment explaining what it's
// for and (when useful) where to get it.
//
// Idempotent. Safe to re-run after editing the design.

import { readFileSync, writeFileSync, existsSync } from "fs";
import { join } from "path";

const OUTPUT_FILE = "backend-design.env.example";

const STATE_FILES = ["endpoints.json", "forms.json", "auth.json"];

function anyMultipart(state) {
  const eps = state.endpoints ?? [];
  if (eps.some((ep) => ep.content_type === "multipart/form-data")) return true;
  const forms = state.forms?.forms ?? [];
  return forms.some((f) => f.multipart === true);
}

export function renderEnvExample(cwd = process.cwd()) {
  const state = loadState(cwd);
  const config = loadJson(join(cwd, ".backend-design", "config.json")) ?? {};
  const sections = buildSections(state, config);

  const lines = [];
  lines.push("# Generated by backend-design.");
  lines.push("# Copy to .env and fill in values before running the scaffolded backend.");
  lines.push("# Re-run `npx backend-design gaps` after filling values to refresh blocker count.");
  lines.push("");

  for (const section of sections) {
    if (!section.vars.length) continue;
    lines.push(`# ${"=".repeat(60)}`);
    lines.push(`# ${section.title}`);
    lines.push(`# ${"=".repeat(60)}`);
    for (const v of section.vars) {
      if (v.comment) {
        for (const line of v.comment.split("\n")) lines.push(`# ${line}`);
      }
      const value = v.default ?? "";
      const prefix = v.commented ? "# " : "";
      lines.push(`${prefix}${v.name}=${value}`);
      lines.push("");
    }
  }

  return lines.join("\n").replace(/\n{3,}/g, "\n\n");
}

function buildSections(state, config) {
  const auth = state.auth;
  const endpoints = state.endpoints ?? [];
  const stackId = config?.stack?.id ?? "";
  const database = config?.stack?.database;

  const sections = [];

  // Database
  if (database === "postgres") {
    sections.push({
      title: "Database",
      vars: [
        {
          name: "DATABASE_URL",
          comment: "PostgreSQL connection string.\nLocal dev example: postgresql://postgres:postgres@localhost:5432/myapp\nProvisioning: Neon (https://neon.tech), Supabase, RDS, or `docker run postgres`.",
        },
      ],
    });
  }

  // Auth
  if (auth?.strategy === "jwt") {
    const v = auth.secret_env ?? "JWT_SECRET";
    sections.push({
      title: "Auth",
      vars: [
        {
          name: v,
          comment: "JWT signing secret. Generate with: openssl rand -hex 32",
        },
      ],
    });
  }
  if (auth?.strategy === "session") {
    const vars = [
      {
        name: "SESSION_SECRET",
        comment: "Session cookie signing/encryption secret. Generate with: openssl rand -base64 32",
      },
    ];
    if (auth.store === "redis") {
      vars.push({
        name: "REDIS_URL",
        comment: "Redis connection URL (e.g. redis://localhost:6379). Required because auth.store is 'redis'.",
      });
    }
    vars.push({
      name: "SESSION_MAX_AGE_DAYS",
      comment: "Session cookie max-age in days. Optional — defaults to 7.",
      default: "7",
      commented: true,
    });
    sections.push({ title: "Sessions", vars });
  }

  // Webhooks (per source)
  const webhookSources = new Set();
  for (const ep of endpoints) {
    if (!ep.is_webhook) continue;
    const source = (ep.webhook_source ?? "").toLowerCase().trim();
    if (source) webhookSources.add(source);
  }
  if (webhookSources.size) {
    const vars = [];
    for (const source of [...webhookSources].sort()) {
      const upper = source.toUpperCase();
      vars.push({
        name: `${upper}_WEBHOOK_SECRET`,
        comment: webhookHint(source),
      });
    }
    sections.push({ title: "Webhook signing secrets", vars });
  }

  // Outbound third-party API keys
  const externalKeys = [];
  if (endpoints.some((ep) => ep.is_external && /stripe/i.test(ep.external_origin ?? ""))) {
    externalKeys.push({
      name: "STRIPE_SECRET_KEY",
      comment: "Stripe API secret key (Dashboard → Developers → API keys).",
    });
  }
  if (endpoints.some((ep) => ep.is_external && /openai/i.test(ep.external_origin ?? ""))) {
    externalKeys.push({
      name: "OPENAI_API_KEY",
      comment: "OpenAI API key (https://platform.openai.com/api-keys).",
    });
  }
  if (endpoints.some((ep) => ep.is_external && /supabase/i.test(ep.external_origin ?? ""))) {
    externalKeys.push(
      { name: "SUPABASE_URL", comment: "Supabase project URL (Dashboard → Settings → API)." },
      { name: "SUPABASE_ANON_KEY", comment: "Supabase anon/public key." }
    );
  }
  if (externalKeys.length) {
    sections.push({ title: "Outbound API keys", vars: externalKeys });
  }

  // OAuth providers
  const providers = auth?.oauth_providers ?? [];
  if (providers.length) {
    const vars = [];
    for (const p of providers) {
      const name = typeof p === "string" ? p : p?.name;
      if (!name) continue;
      const upper = name.toUpperCase();
      vars.push(
        { name: `${upper}_CLIENT_ID`, comment: oauthHint(name) },
        { name: `${upper}_CLIENT_SECRET`, comment: null }
      );
    }
    if (vars.length) sections.push({ title: "OAuth providers", vars });
  }

  // Email (any auth flow that needs it)
  if (auth?.password_reset || auth?.email_verification) {
    sections.push({
      title: "Email delivery (pick ONE provider)",
      vars: [
        {
          name: "RESEND_API_KEY",
          comment: "Recommended for new projects. Get at https://resend.com/api-keys.",
          commented: true,
        },
        {
          name: "SENDGRID_API_KEY",
          comment: "Mature, generous free tier. https://app.sendgrid.com/settings/api_keys.",
          commented: true,
        },
        {
          name: "MAILGUN_API_KEY",
          comment: "Good for high volume. https://app.mailgun.com/app/sending/domains.",
          commented: true,
        },
        {
          name: "POSTMARK_API_KEY",
          comment: "Best transactional deliverability. https://account.postmarkapp.com/api_tokens.",
          commented: true,
        },
        {
          name: "SMTP_HOST",
          comment: "Generic SMTP fallback. Also set SMTP_PORT, SMTP_USER, SMTP_PASS.",
          commented: true,
        },
      ],
    });
  }

  // File uploads
  const hasMultipart = anyMultipart(state);
  if (hasMultipart) {
    sections.push({
      title: "File uploads",
      vars: [
        {
          name: "UPLOADS_DIR",
          comment: "Local directory for uploaded files. For prod, swap codegen's lib/storage stub for S3/R2.",
          default: "./uploads",
        },
      ],
    });
  }

  // Runtime
  const nodeStack = stackId.startsWith("node-") || stackId === "nextjs-prisma";
  sections.push({
    title: "Runtime",
    vars: [
      {
        name: "NODE_ENV",
        comment: nodeStack
          ? "Set to 'production' in deploy. Affects logging, error detail, and placeholder behavior."
          : "Set to 'production' in deploy.",
        default: "development",
      },
      ...(nodeStack
        ? [
            {
              name: "PORT",
              comment: "HTTP port the server binds to.",
              default: "3000",
            },
          ]
        : []),
    ],
  });

  // Security baseline (every server stack)
  const isServer = stackId !== "s2ai-schema";
  if (isServer) {
    const securityVars = [
      {
        name: "ALLOWED_ORIGINS",
        comment:
          "Comma-separated list of origins permitted by CORS. The server refuses to start in production if this is unset or contains '*'.",
        default: "http://localhost:3000",
      },
      {
        name: "LOG_LEVEL",
        comment:
          "Log level: trace | debug | info | warn | error. Dev defaults to 'debug' with pretty output; production stays JSON.",
        default: "info",
      },
      {
        name: "RATE_LIMIT_MAX",
        comment: "Global rate limit (requests per 15-minute window per IP).",
        default: "1000",
      },
      {
        name: "RATE_LIMIT_WRITE_MAX",
        comment: "Tighter limit applied to POST/PATCH/DELETE routes.",
        default: "100",
      },
    ];
    if (stackId === "nextjs-prisma") {
      securityVars.push({
        name: "UPSTASH_REDIS_URL",
        comment:
          "Optional: enables shared rate limiting across Vercel function invocations via @upstash/ratelimit. Without it, an in-memory limiter is used (fine for single-instance / dev).",
        commented: true,
      });
    }
    sections.push({ title: "Security baseline", vars: securityVars });
  }

  return sections;
}

function webhookHint(source) {
  switch (source) {
    case "stripe":
      return "Stripe Dashboard → Developers → Webhooks → click endpoint → 'Signing secret'.";
    case "github":
      return "GitHub repo → Settings → Webhooks → click webhook → 'Secret' (you set this when creating the hook).";
    case "shopify":
      return "Shopify Admin → Settings → Notifications → Webhooks → 'Signed with secret'.";
    case "slack":
      return "Slack app → Basic Information → Signing Secret.";
    default:
      return `Signing secret for ${source} webhooks — check the provider's webhook settings.`;
  }
}

function oauthHint(name) {
  switch (name.toLowerCase()) {
    case "google":
      return "Google Cloud Console → APIs & Services → Credentials → OAuth 2.0 Client IDs (https://console.cloud.google.com/apis/credentials).";
    case "github":
      return "GitHub → Settings → Developer settings → OAuth Apps → New OAuth App.";
    case "discord":
      return "Discord Developer Portal → Applications → OAuth2 (https://discord.com/developers/applications).";
    case "apple":
      return "Apple Developer → Certificates, IDs & Profiles → Identifiers → Services IDs.";
    default:
      return `OAuth credentials for ${name} — check the provider's developer portal.`;
  }
}

function loadState(cwd) {
  const dir = join(cwd, ".backend-design", "state");
  const out = {};
  for (const f of STATE_FILES) {
    const p = join(dir, f);
    if (!existsSync(p)) continue;
    try {
      out[f.replace(".json", "")] = JSON.parse(readFileSync(p, "utf8"));
    } catch {
      // Skip; validator surfaces parse errors.
    }
  }
  return out;
}

function loadJson(path) {
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

export function runRender(cwd = process.cwd()) {
  const config = loadJson(join(cwd, ".backend-design", "config.json")) ?? {};
  if (config?.stack?.id === "s2ai-schema") {
    return null;
  }
  const out = renderEnvExample(cwd);
  writeFileSync(join(cwd, OUTPUT_FILE), out.endsWith("\n") ? out : out + "\n");
  return out;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const result = runRender();
  if (result === null) {
    console.log(`Skipped ${OUTPUT_FILE} (s2ai-schema stack has no server to configure).`);
  } else {
    console.log(`Wrote ./${OUTPUT_FILE}`);
  }
}
